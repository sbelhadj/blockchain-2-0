from figlib import *
F = Fig(9.6, 4.6)
def b(x, y, w, h, col, t, s=""):
    F.box(x, y, w, h, color=col); own = (x, y, x + w, y + h)
    F.text(x + w / 2, y + h - 20 if s else y + h / 2, t, size=9, weight="bold", owner=own)
    if s: F.text(x + w / 2, y + 20, s, size=7.8, owner=own)
F.text(220, 445, "Web application", size=10.5, weight="bold")
F.text(690, 445, "Decentralized application", size=10.5, weight="bold")
F.line(450, 20, 450, 455, color="#BFBFBF", lw=0.8, ls="--")
b(130, 360, 180, 55, "grey", "Browser UI", "HTML, JS")
